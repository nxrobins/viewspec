def init_design_file(path: str | Path = "DESIGN.md", *, force: bool = False) -> Path:
    output = Path(path)
    if output.exists() and not force:
        raise ValueError(f"{output} already exists; pass --force to overwrite")
    atomic_write(output, STARTER_DESIGN)
    return output


